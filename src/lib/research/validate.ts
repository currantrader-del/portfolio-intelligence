/**
 * Validation before approval. Re-checks a finished investigation from what it saved, by code and at no
 * AI cost: the valuation arithmetic, where every valuation input comes from, the cited findings, the
 * documents (including the earnings-call Q&A), how sensitive the value is to its weakest inputs, and a
 * bridge from an earlier version's value. It never changes the research; the report is saved on its own.
 */
import type { ReviewAnnotations } from "./review";
import { computeValuation, valueScenario, type ScenarioName, type ScenarioSpec } from "./investigate/valuationCalc";

export type CheckStatus = "pass" | "warn" | "fail";
export type ValidationCheck = { key: string; label: string; status: CheckStatus; detail: string };
export type InputSource = { scenario: ScenarioName; input: string; value: number; kind: "finding" | "calculation" | "estimate"; cites: string[]; weakCites: string[]; note: string };
export type Sensitivity = { label: string; weighted: number; delta: number; annualized: number | null };
export type BridgeStep = { label: string; from: number; to: number; delta: number };
export type ValidationReport = {
  version: "validate@1";
  symbol: string;
  at: string;
  verdict: "passes" | "passes_with_caveats" | "does_not_pass";
  headline: string;
  checks: ValidationCheck[];
  inputs: InputSource[];
  sensitivity: Sensitivity[];
  bridges: { title: string; steps: BridgeStep[]; note: string }[];
  /** A reviewer's own notes, added when the report is saved (never generated by AI). */
  notes: string[];
  /** Reviewer corrections laid over the record when it is shown and used (see review.ts); the record is not changed. */
  annotations?: ReviewAnnotations | null;
};

type Finding = { id: string; check?: { status?: string } | null; source?: string; key?: boolean | string };
type InvDoc = { id: string; kind?: string; status?: string; required?: boolean | string; title?: string };
type ReviewNote = { docId?: string; qa?: unknown[] };
type LogLine = { note?: string; step?: string };
export type SavedValuation = { specs: ScenarioSpec[]; result: { weighted_value: number | null; annualized_return: number | null; scenarios: { name: ScenarioName; value_per_share: number }[] }; horizon_date: string };
export type PriorVersion = { label: string; bear: number; base: number; bull: number; pBear: number; pBase: number; pBull: number; specs?: ScenarioSpec[] };

const r2 = (n: number) => Math.round(n * 100) / 100;
const STRONG = new Set(["verified", "calculation"]);

/** Splits "estimate: x (F5) plus (F8, F14)" into its kind and the finding ids it cites. */
export function classifySource(src: string): { kind: InputSource["kind"]; cites: string[] } {
  const s = String(src ?? "").trim();
  const cites = [...new Set(s.match(/\bF\d+\b/g) ?? [])];
  if (/^F\d+$/.test(s)) return { kind: "finding", cites };
  if (/^calc/i.test(s)) return { kind: "calculation", cites };
  return { kind: "estimate", cites };
}

const weighted = (specs: ScenarioSpec[], horizon: string, price: number, today: string) => {
  const r = computeValuation({ scenarios: specs, horizon_date: horizon, price, today });
  return { w: r.weighted_value ?? NaN, ann: r.annualized_return, r };
};

function tweak(specs: ScenarioSpec[], scen: ScenarioName | "all", f: (s: ScenarioSpec) => ScenarioSpec) {
  return specs.map((s) => (scen === "all" || s.name === scen ? f(s) : s));
}

export function validateInvestigation(a: {
  symbol: string;
  valuation: SavedValuation;
  price: number;
  today: string;
  findings: Finding[];
  inventory: InvDoc[];
  reviews: ReviewNote[];
  log?: LogLine[];
  prior?: PriorVersion[];
  notes?: string[];
  now?: Date;
}): ValidationReport {
  const checks: ValidationCheck[] = [];
  const { specs } = a.valuation;
  const byId = new Map(a.findings.map((f) => [f.id, f]));

  // 1. Arithmetic: recompute every scenario and the weighted value from the saved inputs.
  const re = weighted(specs, a.valuation.horizon_date, a.price, a.today);
  const savedW = a.valuation.result.weighted_value ?? NaN;
  const scenOk = a.valuation.result.scenarios.every((s) => Math.abs((re.r.scenarios.find((x) => x.name === s.name)?.value_per_share ?? NaN) - s.value_per_share) < 0.011);
  const arithOk = scenOk && Math.abs(re.w - savedW) < 0.011 && re.r.errors.length === 0;
  checks.push({ key: "arithmetic", label: "Valuation arithmetic", status: arithOk ? "pass" : "fail",
    detail: arithOk ? `Recomputed independently: bear $${re.r.scenarios.find((s) => s.name === "bear")?.value_per_share}, base $${re.r.scenarios.find((s) => s.name === "base")?.value_per_share}, bull $${re.r.scenarios.find((s) => s.name === "bull")?.value_per_share}, weighted $${re.w}, ${((re.ann ?? 0) * 100).toFixed(1)}% a year. Matches what was saved.` : `Recomputed weighted value $${re.w} vs saved $${savedW}${re.r.errors.length ? `; ${re.r.errors.join("; ")}` : ""}` });

  // 2. Where every valuation input comes from.
  const inputs: InputSource[] = [];
  for (const s of specs) for (const [k, v] of Object.entries(s.inputs)) {
    if (typeof v !== "number") continue;
    const { kind, cites } = classifySource(s.sources?.[k] ?? "");
    const weakCites = cites.filter((id) => !STRONG.has(String(byId.get(id)?.check?.status ?? "missing")));
    inputs.push({ scenario: s.name, input: k, value: v, kind, cites, weakCites, note: String(s.sources?.[k] ?? "") });
  }
  const est = inputs.filter((i) => i.kind === "estimate").length;
  const missingCites = inputs.flatMap((i) => i.cites.filter((id) => !byId.has(id)).map((id) => `${i.scenario} ${i.input} cites ${id}, which is not among the findings`));
  checks.push({ key: "inputs", label: "Valuation inputs are sourced", status: missingCites.length ? "fail" : est === inputs.length ? "warn" : "pass",
    detail: `${inputs.length - est} of ${inputs.length} inputs come straight from findings; ${est} are labelled estimates that cite ${new Set(inputs.flatMap((i) => i.cites)).size} findings as support.${missingCites.length ? ` ${missingCites.join("; ")}.` : ""} Estimates are normal for a forecast; the sensitivity below shows which ones matter.` });
  const weak = [...new Set(inputs.flatMap((i) => i.weakCites))];
  if (weak.length) checks.push({ key: "weak_cites", label: "Findings behind the inputs", status: "warn",
    detail: `Inputs lean on findings that could not be checked against a primary document: ${weak.map((id) => `${id} (${byId.get(id)?.check?.status ?? "missing"})`).join(", ")}.` });

  // 3. Key findings that failed the quote check.
  const keyBad = a.findings.filter((f) => (f.key === true || f.key === "true") && ["quote_not_found", "not_found"].includes(String(f.check?.status)));
  checks.push({ key: "findings", label: "Key findings match their documents", status: keyBad.length ? "warn" : "pass",
    detail: keyBad.length ? `${keyBad.map((f) => f.id).join(", ")}: the quoted text was not found in the cited document, so treat ${keyBad.length === 1 ? "it" : "them"} as unconfirmed.` : `Every key finding's quote was found in its document (or is a labelled calculation, estimate or secondary source).` });

  // 4. Documents: required ones read in full; reader failures recovered.
  const req = a.inventory.filter((d) => d.required === true || d.required === "true");
  const unread = req.filter((d) => d.status !== "fully_reviewed" && d.status !== "reviewed_earlier");
  const failures = (a.log ?? []).flatMap((l) => [...String(l.note ?? "").matchAll(/(D\d+) [^:]+: The reader's notes were not readable/g)].map((m) => m[1]));
  const reviewed = new Set(a.reviews.map((r) => r.docId));
  const unrecovered = [...new Set(failures)].filter((d) => !reviewed.has(d));
  checks.push({ key: "documents", label: "Required documents read", status: unread.length || unrecovered.length ? "fail" : "pass",
    detail: `${req.length - unread.length} of ${req.length} required documents fully reviewed${unread.length ? `; not read: ${unread.map((d) => d.id).join(", ")}` : ""}.${failures.length ? ` Reader notes were cut off at first for ${[...new Set(failures)].join(" and ")}; ${unrecovered.length ? `${unrecovered.join(", ")} never recovered` : "each was read again and readable notes were saved"}.` : ""}` });

  // 5. Earnings-call Q&A (the standard requires it, or a disclosed gap).
  const transcripts = a.inventory.filter((d) => d.kind === "transcript");
  const qa = a.reviews.filter((r) => transcripts.some((t) => t.id === r.docId)).reduce((m, r) => Math.max(m, Array.isArray(r.qa) ? r.qa.length : 0), 0);
  checks.push({ key: "transcript", label: "Earnings-call Q&A reviewed", status: qa > 0 ? "pass" : "fail",
    detail: qa > 0 ? `${transcripts.map((t) => t.title ?? t.id).join(", ")}: ${qa} analyst questions and answers captured.` : transcripts.length ? "A transcript is listed but no analyst Q&A was captured from it." : "No earnings-call transcript was found. The research must say so as a gap." });

  // 6. Sensitivity: how far the weighted value moves on the inputs that are estimates.
  const H = a.valuation.horizon_date;
  const sens: [string, ScenarioSpec[]][] = [
    ["Base multiple 1 turn lower", tweak(specs, "base", (s) => ({ ...s, inputs: { ...s.inputs, multiple: s.inputs.multiple - 1 } }))],
    ["Base multiple 1 turn higher", tweak(specs, "base", (s) => ({ ...s, inputs: { ...s.inputs, multiple: s.inputs.multiple + 1 } }))],
    ["Base net debt $2B higher", tweak(specs, "base", (s) => ({ ...s, inputs: { ...s.inputs, net_debt: (s.inputs.net_debt ?? 0) + 2e9 } }))],
    ["Base net debt $2B lower", tweak(specs, "base", (s) => ({ ...s, inputs: { ...s.inputs, net_debt: (s.inputs.net_debt ?? 0) - 2e9 } }))],
    ["Base revenue 10% lower", tweak(specs, "base", (s) => ({ ...s, inputs: { ...s.inputs, revenue: s.inputs.revenue * 0.9 } }))],
    ["Base revenue 10% higher", tweak(specs, "base", (s) => ({ ...s, inputs: { ...s.inputs, revenue: s.inputs.revenue * 1.1 } }))],
    ["Base shares 30M fewer", tweak(specs, "base", (s) => ({ ...s, inputs: { ...s.inputs, diluted_shares: s.inputs.diluted_shares - 30e6 } }))],
    ["Bear and bull probability 5 points each way (bear 0.32 / bull 0.23)", specs.map((s) => ({ ...s, probability: s.name === "bear" ? s.probability - 0.05 : s.name === "bull" ? s.probability + 0.05 : s.probability }))],
    ["Bear and bull probability 5 points the other way", specs.map((s) => ({ ...s, probability: s.name === "bear" ? s.probability + 0.05 : s.name === "bull" ? s.probability - 0.05 : s.probability }))],
  ];
  const sensitivity: Sensitivity[] = sens.map(([label, sp]) => {
    const x = weighted(sp, H, a.price, a.today);
    return { label: label.replace(/ \(bear .*\)$/, ""), weighted: r2(x.w), delta: r2(x.w - re.w), annualized: x.ann };
  });
  const lo = Math.min(...sensitivity.map((s) => s.weighted)), hi = Math.max(...sensitivity.map((s) => s.weighted));
  checks.push({ key: "sensitivity", label: "Sensitivity to the estimates", status: hi > a.price && lo < a.price ? "warn" : "pass",
    detail: `One reasonable change at a time moves the weighted value between $${r2(lo)} and $${r2(hi)} (price $${a.price}).${hi > a.price && lo < a.price ? " The range straddles today's price, so the sign of the expected return depends on estimates, not on facts." : " The conclusion's direction holds across the range."}` });

  // 7. Bridges from earlier versions.
  const bridges: ValidationReport["bridges"] = [];
  const cur = Object.fromEntries(re.r.scenarios.map((s) => [s.name, { v: s.value_per_share, p: s.probability }])) as Record<ScenarioName, { v: number; p: number }>;
  for (const p of a.prior ?? []) {
    const start = r2(p.pBear * p.bear + p.pBase * p.base + p.pBull * p.bull);
    const steps: BridgeStep[] = [];
    let acc = start;
    for (const [n, old, prob] of [["bear", p.bear, p.pBear], ["base", p.base, p.pBase], ["bull", p.bull, p.pBull]] as const) {
      const d = r2(prob * (cur[n].v - old));
      steps.push({ label: `${n[0].toUpperCase()}${n.slice(1)} value $${old} → $${cur[n].v} (at the old ${Math.round(prob * 100)}% weight)`, from: acc, to: r2(acc + d), delta: d });
      acc = r2(acc + d);
    }
    const pd = r2(re.w - acc);
    steps.push({ label: `Probabilities ${Math.round(p.pBear * 100)}/${Math.round(p.pBase * 100)}/${Math.round(p.pBull * 100)} → ${Math.round(cur.bear.p * 100)}/${Math.round(cur.base.p * 100)}/${Math.round(cur.bull.p * 100)}`, from: acc, to: r2(re.w), delta: pd });
    // With input-level specs on both sides, change one input at a time in the base case.
    if (p.specs) {
      const pb = p.specs.find((s) => s.name === "base"), cb = specs.find((s) => s.name === "base");
      if (pb && cb && pb.method === cb.method) {
        let s = { ...pb, inputs: { ...pb.inputs }, floor_value: null };
        const val = (x: ScenarioSpec) => valueScenario(x).value;
        let prev = val(s);
        for (const k of ["revenue", "ebitda_margin", "operating_margin", "multiple", "net_debt", "diluted_shares"] as const) {
          if (cb.inputs[k] === undefined || cb.inputs[k] === s.inputs[k]) continue;
          s = { ...s, inputs: { ...s.inputs, [k]: cb.inputs[k] } };
          const nv = val(s);
          steps.push({ label: `  base ${k.replace("_", " ")} ${fmtIn(k, pb.inputs[k])} → ${fmtIn(k, cb.inputs[k])}`, from: r2(prev), to: r2(nv), delta: r2(nv - prev) });
          prev = nv;
        }
      }
    }
    bridges.push({ title: `From ${p.label} ($${start}) to now ($${re.w})`, steps, note: p.specs ? "Indented lines split the base case change into one input at a time, in the order shown; the order changes the size of each step, not the total." : "The earlier version saved only its scenario values, not its inputs, so this bridge works at the scenario level." });
  }

  const fails = checks.filter((c) => c.status === "fail");
  const warns = checks.filter((c) => c.status === "warn");
  const verdict: ValidationReport["verdict"] = fails.length ? "does_not_pass" : warns.length ? "passes_with_caveats" : "passes";
  const headline = fails.length ? `Does not pass: ${fails.map((c) => c.label.toLowerCase()).join("; ")}.`
    : `${verdict === "passes" ? "Passes" : "Passes with caveats"}: the arithmetic, documents and Q&A check out${warns.length ? `; ${warns.length} caveat${warns.length === 1 ? "" : "s"} below` : ""}.`;
  return { version: "validate@1", symbol: a.symbol, at: (a.now ?? new Date()).toISOString(), verdict, headline, checks, inputs, sensitivity, bridges, notes: a.notes ?? [] };
}

function fmtIn(k: string, v: number | undefined) {
  if (v === undefined) return "—";
  if (k === "revenue" || k === "net_debt") return `$${r2(v / 1e9)}B`;
  if (k === "diluted_shares") return `${Math.round(v / 1e6)}M`;
  if (k.endsWith("margin")) return `${Math.round(v * 100)}%`;
  return `${v}x`;
}
